#!/usr/bin/env bash
# 把已经 cmake --install 过的 staging 目录组装成 Arch 的 .pkg.tar.zst。
#
# 为什么不用 makepkg：这台机器上 makepkg 跑不起来 ——
#   * 它拒绝 root 运行，而 su / runuser / unshare 都被环境拦（setgroups 不允许）；
#   * 它的下载走 /dev/fd/63，解包走 bsdtar（utime 被拦），编译阶段 gcc 探测
#     -I 目录的操作会被安全策略拒成 EPERM，直接把构建打断。
# 所以这里改成：先用仓库里已经验证过的构建产物 cmake --install 到 staging，
# 再手写 .PKGINFO 打包。pacman 认这种包（.MTREE / .BUILDINFO 是可选的）。
#
# 用法：
#   bash .workbuddy/tools/make_arch_pkg.sh <staging 目录> <pkgver> [输出目录]
# 例：
#   DESTDIR=$PWD/build-linux/pkgroot cmake --install build-linux --prefix /usr
#   bash .workbuddy/tools/make_arch_pkg.sh build-linux/pkgroot 1.0.4 dist
set -euo pipefail

STAGE=${1:?用法: make_arch_pkg.sh <staging 目录> <pkgver> [输出目录]}
PKGVER=${2:?缺 pkgver}
OUT=${3:-.}
PKGNAME=cppsekai
PKGREL=1

[ -d "$STAGE/usr" ] || { echo "[pkg] $STAGE/usr 不存在 —— 先 cmake --install 到这个目录"; exit 1; }

mkdir -p "$STAGE"
SIZE=$(du -sb "$STAGE/usr" | cut -f1)
BUILDDATE=$(date +%s)

cat > "$STAGE/.PKGINFO" <<EOF
# Generated by .workbuddy/tools/make_arch_pkg.sh
pkgname = $PKGNAME
pkgbase = $PKGNAME
pkgver = $PKGVER-$PKGREL
pkgdesc = Project SEKAI style SUS chart player (Linux port)
url = https://github.com/arcwolf1/cppsekai-linux
builddate = $BUILDDATE
packager = Arcwolf <arcwolf@arcwolf.top>
size = $SIZE
arch = x86_64
license = AGPL-3.0-only
depend = sdl2
depend = gtk3
depend = curl
depend = fontconfig
EOF

# LICENSE 不属于 cmake 的 install 规则，AUR 的 PKGBUILD 里是 install -Dm644 装的
install -Dm644 LICENSE "$STAGE/usr/share/licenses/$PKGNAME/LICENSE"

TARGET="$OUT/$PKGNAME-$PKGVER-$PKGREL-x86_64.pkg.tar.zst"
mkdir -p "$OUT"
rm -f "$TARGET"
tar --zstd -cf "$TARGET" -C "$STAGE" .PKGINFO usr

echo "[pkg] $TARGET"
ls -lh "$TARGET"
